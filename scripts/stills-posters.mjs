/**
 * Writes src/data/showcase/scenes/walk-posters.ts: each walkthrough's first still as a tiny inline preview (40 px wide
 * webp as a data URI, well under a kilobyte). The tab shows it the moment it opens, scaled up (soft, not blank), and the
 * real still fades in over it once it has arrived and decoded, so the film's stage is never an empty card while the
 * still downloads. Re-run after recapturing a film's first still:
 *   node scripts/stills-posters.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const sharp = createRequire(import.meta.url)("sharp");
// The first cue's still of each film (nwks-admin.ts and duffer-cc.ts cues[0]).
const FIRST = ["/images/showcase/nwks/dashboard.webp", "/images/showcase/duffer/dashboard.webp"];
const out = {};
for (const src of FIRST) {
  const buf = await sharp(path.join(ROOT, "public", src)).resize({ width: 40 }).webp({ quality: 60 }).toBuffer();
  out[src] = `data:image/webp;base64,${buf.toString("base64")}`;
}
const body = `// Generated by scripts/stills-posters.mjs: do not edit by hand.
// Each walkthrough's first still as a tiny inline preview, shown until the real still has arrived (StillsWalkthrough).
export const WALK_POSTERS: Readonly<Record<string, string>> = ${JSON.stringify(out, null, 2)};
`;
fs.writeFileSync(path.join(ROOT, "src", "data", "showcase", "scenes", "walk-posters.ts"), body);
console.log(Object.entries(out).map(([k, v]) => `${k}: ${v.length} chars`).join("\n"));
